import json, re, sys, html
from mastery_spec import SPEC
def page_html(s):
    s=re.sub(r'<span class="frac"><span class="nu">(.*?)</span><span class="de">(.*?)</span></span>',r'<span class="fr"><span>\1</span><span>\2</span></span>',s)
    s=re.sub(r'<span class="rad">√<span class="ov">(.*?)</span></span>',r'√<span style="border-top:1px solid currentColor">\1</span>',s)
    return s
def plain(s):
    s=re.sub(r'<span class="frac"><span class="nu">(.*?)</span><span class="de">(.*?)</span></span>',r'(\1)/(\2)',s)
    s=re.sub(r'<span class="rad">√<span class="ov">(.*?)</span></span>',r'√(\1)',s)
    s=re.sub(r'<sup>(.*?)</sup>',r'^(\1)',s); s=s.replace('<br>','; ')
    s=re.sub(r'</?[a-zA-Z][^>]*>','',s)
    return html.unescape(re.sub(r'\s+',' ',s)).strip()
def js(v): return json.dumps(v,ensure_ascii=False)
out=['// Case-file sheets: the Mastery questions from the free worksheets (lab.mathsforensics.com/sheets).',
     '// Generated by worksheets/casefile/to_bank.py from the sheet JSON and mastery_spec.py. Do not edit by hand.',
     'import type { Scheme } from "../schemes.ts";','','export const CASE_FILES: Scheme[] = [']
names={}
CONTEXT={("geo-pythagoras-trig",1):("A cuboid ABCDEFGH measures 3 cm by 4 cm by 12 cm, with base ABCD.","For this cuboid, find the angle between AG and the base ABCD."),
 ("geo-pythagoras-trig",3):("A square-based pyramid has a base of side 6 cm. The apex is directly above the centre of the base, and each sloping edge is 7 cm.","Find the angle between a sloping edge and the base."),
 ("prob-probability",1):("A bag has 4 red and 6 blue sweets. Two are taken without replacement.","Find the probability that at least one sweet is red."),
 ("prob-venn-diagrams",1):("40 people were surveyed. 25 are in group A, 22 in group B, and 5 are in neither.","A person in A is chosen at random. Find the probability they are also in B."),
 ("num-speed-distance-time",1):("The speed-time graph shows a car pulling away from a crime scene, then stopping at a checkpoint.","Work out the car's acceleration in the first 4 seconds.")}
for f,specs in SPEC.items():
    d=json.load(open(f+".json")); code="CF-"+d["code"].split("MF-CF-",1)[1]
    names[code]=re.sub(r'<[^>]+>','',d["title"])
    start=len(d["sections"]["s"]["questions"])+len(d["sections"]["e"]["questions"])
    for i,(q,sp) in enumerate(zip(d["sections"]["m"]["questions"],specs)):
        n=start+i+1
        if (f,i) in CONTEXT:
            q=dict(q); q["text"]=list(CONTEXT[(f,i)])
            if not q.get("svg") and d["sections"]["m"]["questions"][i-1].get("svg"): q["svg"]=d["sections"]["m"]["questions"][i-1]["svg"]
        prompt="<br>".join(page_html(t) for t in q["text"])
        if q.get("eqs"): prompt+="<br>"+"<br>".join(f'<span class="eq">{page_html(e)}</span>' for e in q["eqs"])
        ptxt=" ".join(plain(t) for t in q["text"]+q.get("eqs",[]))
        show=bool(re.search(r'^(Show|Prove|Explain|Use the angle)',plain(q["text"][0])))
        pts=[];mids=[]
        cnt={}
        for p in sp["pts"]:
            code1,crit=p[0],p[1]; cnt[code1]=cnt.get(code1,0)+1
            pid=f"{code1}{'abcdefgh'[cnt[code1]-1]}"
            o={"id":pid,"code":code1,"criterion":crit}
            if code1=="A1" and mids: o["dep"]=list(mids)
            if len(p)>2: o["accept"]=p[2]
            if code1=="M1": mids.append(pid)
            pts.append(o)
        sol=[x.strip() for x in re.split(r'(?<=\.)\s+',plain(q.get("working","")) ) if x.strip()]+[plain(q["answer"])]
        s={"id":f"cf-{f.split('-',1)[1]}-q{n}","source":{"paper":code,"q":str(n)},"topic":sp["topic"],"tier":"H","calculator":not d["code"].endswith(("EXACTTRIG","SURDS","INDICES")),
           "prompt":prompt,"promptText":ptxt,"marks":q["marks"],"answer":plain(q["answer"]),"solution":sol,"noWorking":"zero" if show else "answer","points":pts}
        if q.get("svg"): s["diagram"]='<div style="background:#fff;border-radius:8px;padding:6px;display:inline-block;max-width:100%">'+re.sub(r'style="width:[0-9.]+mm;height:[0-9.]+mm;[^"]*"','style="max-width:100%;width:340px;height:auto;display:block"',q["svg"])+'</div>'
        if sp["errors"]: s["errors"]=[{"id":a,"looksLike":b} for a,b in sp["errors"]]
        s["coach"]={"keyWords":[{"text":sp["key"][0],"why":sp["key"][1]}],"clues":sp["clues"],"traps":[sp["trap"]] if sp["trap"] else []}
        if not show: s["showWorking"]="Write each step, so the method marks can be given."
        out.append("  "+js(s)+",")
out.append("];")
out.append("export const CASE_FILE_NAMES: Record<string, string> = "+js(names)+";")
open(sys.argv[1],"w").write("\n".join(out)+"\n")
print(sum(len(v) for v in SPEC.values()),"questions,",len(names),"sheets")
print(js(names))
